def connectors(pid):
    a = AUTO[pid]
    out = [dict(c, n=c.get('n', '')) for c in a['conns']]
    if pid in MOTORS:
        off = [16.5, 0, -1.3]   # 모터 표준 좌표 = 몸통 가운데 (전선 제외)
        out = [dict(c, t='SERVO' if pid == 'servo-digital' else 'DCUT', p=[R1(c['p'][k] + off[k]) for k in range(3)], n='출력 축' + (' (아래)' if c['a'][1] < 0 else '')) for c in out] + motor()
    if pid in MANUAL: out += MANUAL[pid]
    # 같은 위치 · 종류가 두 번 잡힌 것 (프레임 그룹과 안쪽 PCB가 같은 구멍 목록을 가짐) 하나로
    seen, uniq = set(), []
    for c in out:
        k = (c['t'], tuple(c['p']))
        if k not in seen: seen.add(k); uniq.append(c)
    out = uniq
    if pid in EL3: out.append(C('E3P_M', (0, 0, 0), (0, 1, 0), '3핀 헤더 S · + · −'))
    return out

def summarize(conns):
    by = {}
    for c in conns: by.setdefault(c['t'], []).append(c)
    parts = []
    for t, cs in by.items():
        xs = sorted(set(c['p'][0] for c in cs)); zs = sorted(set(c['p'][2] for c in cs)); ys = sorted(set(c['p'][1] for c in cs))
        if len(cs) > 6:
            parts.append(f'{t} × {len(cs)} (x {xs[0]} ~ {xs[-1]}, z {zs[0]} ~ {zs[-1]}, 면 y {ys[0]}{"~" + str(ys[-1]) if len(ys) > 1 else ""})')
        else:
            parts.append(f'{t} × {len(cs)}: ' + ' · '.join(f'({c["p"][0]}, {c["p"][1]}, {c["p"][2]})' for c in cs))
    return '<br>'.join(parts)

