R1 = lambda v: round(v, 1)

# ───────── 자동으로 못 뽑은 부품의 연결점 (표준 좌표: 가운데 · 바닥 = 0, 위 +Y, 앞 −Z) ─────────
def C(t, p, a=(0, 1, 0), n=''):
    return {'t': t, 'p': [R1(v) for v in p], 'a': list(a), 'n': n}

def lframe(a, b, w, angle=90, wp=10, tap=False, off=(0, 0, 0)):
    """makeLFrame과 같은 식: 바닥 다리는 −X로 a구멍, 세운 다리는 (180 − angle)° 기울어 b구멍, 폭 w구멍 (간격 wp)"""
    W = (w - 1) * wp + 8
    t = 'TAP' if tap else 'M3'
    out = []
    phi = math.radians(180 - angle)
    for i in range(a):
        for j in range(w):
            p = (-(4 + 10 * i), 1, -W / 2 + 4 + j * wp)
            out.append(C(t, [p[k] + off[k] for k in range(3)], (0, 1, 0), f'바닥 다리 {i + 1}-{j + 1}'))
    for i in range(b):
        for j in range(w):
            u = 4 + 10 * i
            p = (u * math.cos(phi), u * math.sin(phi), -W / 2 + 4 + j * wp)
            out.append(C(t, [p[k] + off[k] for k in range(3)], (R1(-math.sin(phi)), R1(math.cos(phi)), 0), f'세운 다리 {i + 1}-{j + 1}'))
    return out

